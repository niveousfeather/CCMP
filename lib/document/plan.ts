function buildTrainingPlanFromIntent(intent: WordGenerationIntent): WordDocumentPlan {
  const plan = buildProposalPlanFromIntent({ ...intent, documentType: "proposal" });
  const duration = displayValue(intent.duration, /三天|3天|三日|3日/.test(`${intent.duration || ""} ${intent.mustInclude.join(" ")}`) ? "三天" : "按培训周期推进");
  const focus = focusText(intent);
  const anchors = scopeOrAnchors(intent, [focus]);
  const requiresThreeDayFlow = /三天|3天|三日|3日/.test(`${intent.duration || ""} ${intent.mustInclude.join(" ")} ${intent.requirements.join(" ")}`);
  const normalizedSections = plan.sections
    .filter((section) => /时间安排|责任分工|验收标准|评价指标|风险/.test(section.heading))
    .filter((section) => !(requiresThreeDayFlow && /时间安排/.test(section.heading)))
    .map((section) => {
      if (/时间安排/.test(section.heading)) {
        return {
          ...section,
          heading: requiresThreeDayFlow ? "三天培训流程与时间安排" : "培训流程与时间安排",
          intro: requiresThreeDayFlow
            ? `三天培训流程按“认知导入、岗位实践、考核复盘”推进，确保${intent.topic}的新员工培训有明确节奏和阶段产出。`
            : section.intro
        };
      }
      if (/验收标准|评价指标/.test(section.heading)) {
        return {
          ...section,
          heading: "考核方式与评价标准",
          intro: `考核方式围绕${focus}设置，兼顾知识理解、岗位实践、过程记录和复盘改进，避免只看签到不看学习成效。`
        };
      }
      if (/风险/.test(section.heading)) {
        return {
          ...section,
          heading: "风险预案",
          intro: `风险预案聚焦${intent.topic}培训中可能出现的时间冲突、导师缺位、学习吸收不足和考核反馈滞后。`
        };
      }
      return section;
    });
  return {
    ...plan,
    title: makeTitleFromIntent(intent, "培训方案"),
    documentType: "training_plan",
    sections: [
      {
        heading: "培训目标",
        level: 1,
        intro: `培训方案面向${displayValue(intent.audience, "参训对象")}，围绕${focus}提升制度理解、岗位操作、协作沟通和复盘改进能力。`,
        blocks: [{ type: "paragraph", text: `培训成果应能支撑${intent.topic}在真实岗位场景中的应用，学员完成后能够说明关键流程、完成基础任务并接受考核反馈。` }]
      },
      {
        heading: "培训内容",
        level: 1,
        intro: `培训内容按${anchorText(intent)}组织，兼顾讲解、演示、练习、反馈和成果提交。`,
        blocks: [{ type: "table", headers: ["模块", "训练重点"], rows: anchors.map((item) => [item, `围绕${item}设置讲解、演示、任务练习和现场答疑。`]) }]
      },
      ...(requiresThreeDayFlow
        ? [
            {
              heading: "三天培训流程与时间安排",
              level: 1 as const,
              intro: `三天流程把${intent.topic}拆成入职认知、岗位实践和考核复盘三个阶段，确保每天都有明确产出。`,
              blocks: [
                {
                  type: "timeline" as const,
                  headers: ["时间", "培训安排", "产出"],
                  rows: [
                    ["第一天", "公司制度、组织文化、办公流程和入职规范说明", "入职学习记录与问题清单"],
                    ["第二天", "岗位流程演示、导师带教、场景练习和阶段反馈", "岗位练习成果与导师反馈"],
                    ["第三天", "综合演练、答疑复盘、考核确认和改进建议", "考核结果、补训建议与转正前跟进清单"]
                  ]
                }
              ]
            }
          ]
        : []),
      ...normalizedSections
    ]
  };
}

