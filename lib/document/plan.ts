function looksLikeRawPrompt(markdown: string, blocks: MarkdownBlock[]) {
  const hasHeading = blocks.some((block) => block.type === "heading");
  if (hasHeading) return false;
  const compact = markdown.replace(/\s+/g, "");
  return compact.length > 0 && compact.length < 500;
}

function buildGenericPlan(markdown: string, title: string, template: DocumentTemplate, intent?: WordGenerationIntent): WordDocumentPlan {
  const blocks = parseMarkdown(markdown);
  const resolvedIntent = intent || extractWordGenerationIntent(uniqueIntentSource(title, markdown));
  if (isUsableWordIntent(resolvedIntent) && looksLikeRawPrompt(markdown, blocks)) {
    return buildWordDocumentPlanFromIntent(resolvedIntent, template);
  }

  const planTitle = cleanTitlePart(inferTitle(title, blocks)) || makeTitleFromIntent(resolvedIntent, template === "proposal" ? "方案" : template === "report" ? "报告" : "文档");
  const sections: WordSection[] = [];
  let current: WordSection | null = null;

  const pushCurrent = () => {
    if (!current) return;
    sections.push(ensureSectionNarrative(current, planTitle));
  };

  for (const block of blocks) {
    if (block.type === "heading") {
      if (block.level === 1 && cleanText(block.text) === planTitle && !current && !sections.length) continue;
      pushCurrent();
      current = { heading: stripHeadingNumber(block.text), level: Math.min(Math.max(block.level, 1), 4) as 1 | 2 | 3 | 4, blocks: [] };
      continue;
    }

    if (!current) current = { heading: "概述", level: 1, blocks: [] };

    if (block.type === "paragraph") {
      const text = cleanText(block.text, 520);
      if (!text) continue;
      if (!current.intro) current.intro = text;
      else current.blocks.push({ type: "paragraph", text });
    } else if (block.type === "list") {
      current.blocks.push(...listToBlocks(current.heading, block.ordered, block.items));
    } else if (block.type === "table") {
      const table = tableBlock(block.rows);
      if (table) current.blocks.push(lessonProcessTableFromMarkdown(table, current.heading));
    } else if (block.type === "code") {
      const text = cleanText(block.text, 520);
      if (text) current.blocks.push({ type: "callout", title: "补充说明", text });
    }
  }
  pushCurrent();

  const sourceSummary = textFromBlocks(blocks);
  const finalSections = sections.length
    ? sections
    : [
        {
          heading: "概述",
          level: 1 as const,
          intro: sourceSummary || `${planTitle}围绕用户需求整理为正式文档，内容按背景、要点和后续行动展开。`,
          blocks: []
        }
      ];

  return {
    title: planTitle,
    subtitle: sourceSummary.length > 28 ? sourceSummary.slice(0, 90) : undefined,
    documentType: documentTypeFromTemplate(template),
    sections: finalSections
  };
}

function buildLessonPlan(markdown: string, title: string, intent?: WordGenerationIntent): WordDocumentPlan {
  const blocks = parseMarkdown(markdown);
  const source = textFromBlocks(blocks);
  if (!intent && blocks.some((block) => block.type === "heading")) {
    return buildGenericPlan(markdown, title, "lesson_plan");
  }
  return buildLessonPlanFromIntent(intent || extractWordGenerationIntent(uniqueIntentSource(title, source || markdown)));
}

export function buildWordDocumentPlan({
  markdown,
  title,
  template,
  intent
}: {
  markdown: string;
  title: string;
  template: DocumentTemplate;
  prompt?: string;
  intent?: WordGenerationIntent;
}): WordDocumentPlan {
  const modelPlan = parseWordDocumentPlanJson(markdown);
  if (modelPlan) {
    return {
      ...modelPlan,
      documentType: modelPlan.documentType || documentTypeFromIntent(intent || extractWordGenerationIntent(uniqueIntentSource(title, markdown)), template)
    };
  }
  const resolvedIntent = intent || extractWordGenerationIntent(uniqueIntentSource(title, markdown));
  if (template === "lesson_plan") return buildLessonPlan(markdown, title, intent);
  return buildGenericPlan(markdown, title, template, resolvedIntent);
}
