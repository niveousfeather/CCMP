function cleanText(value: unknown, maxLength = 420) {
  return String(value || "")
    .replace(/\s+/g, " ")
    .replace(/(?:Generated by NexusAI|由\s*NexusAI\s*生成|NexusAI\s*智能文档模块|NexusAI)/gi, "")
    .trim()
    .slice(0, maxLength);
}

function isTemplateLabelTitle(value: string) {
  return /^(?:Lesson Plan|Proposal|Document|Meeting Minutes|DocTemplate|Research Report|Formal Document)$/i.test(cleanText(value, 80));
}

function isTableLikeBlock(block: WordBlock) {
  return block.type === "table" || block.type === "rubric" || block.type === "timeline" || block.type === "responsibility_matrix";
}

function blockTexts(block: WordBlock) {
  if (block.type === "paragraph") return [block.text];
  if (block.type === "bullet_list" || block.type === "numbered_list" || block.type === "checklist") return block.items;
  if (isTableLikeBlock(block)) return [block.headers, ...block.rows].flat();
  if (block.type === "callout") return [block.title, block.text];
  return [];
}

function sectionHasBody(section: WordSection) {
  return Boolean(section.intro) || section.blocks.some((block) => block.type === "paragraph" || isTableLikeBlock(block) || block.type === "callout" || block.type === "checklist");
}

function sectionStartsWithUnsupportedList(section: WordSection) {
  if (section.intro) return false;
  const firstBlock = section.blocks[0];
  return firstBlock?.type === "bullet_list" || firstBlock?.type === "numbered_list" || firstBlock?.type === "checklist";
}

