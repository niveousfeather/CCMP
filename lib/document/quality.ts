function appendMissingRequiredSections(plan: WordDocumentPlan, fallbackPlan: WordDocumentPlan, intent?: WordGenerationIntent) {
  const required =
    plan.documentType === "lesson_plan"
      ? REQUIRED_LESSON_SECTIONS
      : plan.documentType
        ? REQUIRED_SECTIONS_BY_TYPE[plan.documentType] || []
        : [];
  const explicitRequired = (intent?.mustInclude || []).filter((item) => !isDeliveryOrStyleRequirement(item));
  if (!required.length && !explicitRequired.length) return plan.sections;

  const sections = [...plan.sections];
  for (const requiredHeading of required) {
    if (sections.some((section) => sectionHeadingMatchesRequired(section, requiredHeading))) continue;
    const fallbackSection = fallbackPlan.sections.find((section) => sectionHeadingMatchesRequired(section, requiredHeading));
    sections.push(fallbackSection || requiredFallbackSection(requiredHeading, plan, intent));
  }
  for (const requiredHeading of explicitRequired) {
    if (sections.some((section) => sectionMatchesRequired(section, requiredHeading))) continue;
    const fallbackSection = fallbackPlan.sections.find((section) => sectionMatchesRequired(section, requiredHeading));
    sections.push(fallbackSection || requiredFallbackSection(requiredHeading, plan, intent));
  }
  return sections;
}

