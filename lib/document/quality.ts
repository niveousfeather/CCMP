function chineseOrdinalToArabic(value: string) {
  if (/^\d+$/.test(value)) return value;
  const map: Record<string, number> = {
    一: 1,
    二: 2,
    两: 2,
    三: 3,
    四: 4,
    五: 5,
    六: 6,
    七: 7,
    八: 8,
    九: 9,
    十: 10
  };
  if (map[value]) return String(map[value]);
  const tenMatch = value.match(/^十([一二三四五六七八九])$/);
  if (tenMatch) return String(10 + map[tenMatch[1]]);
  const compoundMatch = value.match(/^([一二三四五六七八九])十([一二三四五六七八九])?$/);
  if (compoundMatch) return String(map[compoundMatch[1]] * 10 + (compoundMatch[2] ? map[compoundMatch[2]] : 0));
  return "";
}

function chapterKeywordAliases(keyword: string) {
  const match = cleanText(keyword, 40).match(/^第([一二两三四五六七八九十百千万\d]+)(章节|章|节)$/);
  if (!match) return [];
  const ordinal = match[1];
  const arabic = chineseOrdinalToArabic(ordinal);
  return uniqueValues([
    `第${ordinal}章节`,
    `第${ordinal}章`,
    `第${ordinal}节`,
    arabic ? `第${arabic}章节` : "",
    arabic ? `第${arabic}章` : "",
    arabic ? `第${arabic}节` : "",
    `${ordinal}章节`,
    `${ordinal}章`,
    `${ordinal}节`
  ].filter(Boolean));
}

function keywordAliases(keyword: string) {
  const key = compact(keyword);
  const group = KEYWORD_SYNONYM_GROUPS.find((items) => items.some((item) => key.includes(compact(item)) || compact(item).includes(key)));
  return uniqueValues([keyword, ...chapterKeywordAliases(keyword), ...(group || [])]);
}

function keywordMatches(compactText: string, keyword: string) {
  const key = compact(keyword);
  if (!key) return false;
  for (const alias of keywordAliases(keyword)) {
    const aliasKey = compact(alias);
    if (aliasKey && compactText.includes(aliasKey)) return true;
  }
  const parts = splitIntentItems(keyword).map(compact).filter((item) => item.length >= 2);
  if (parts.length >= 2) {
    const hits = parts.filter((part) => compactText.includes(part)).length;
    return hits >= Math.ceil(parts.length * 0.6);
  }
  if (key.length >= 8) {
    const grams = new Set<string>();
    for (let index = 0; index <= key.length - 3; index += 2) {
      grams.add(key.slice(index, index + 3));
    }
    const hits = [...grams].filter((gram) => compactText.includes(gram)).length;
    return grams.size > 0 && hits / grams.size >= 0.72;
  }
  return false;
}

function coreIntentKeywords(intent?: WordGenerationIntent) {
  if (!intent) return [];
  return uniqueValues([
    intent.topic,
    intent.chapter,
    intent.chapterTitle,
    intent.scope,
    intent.duration,
    intent.audience
  ].filter((value): value is string => Boolean(value)))
    .filter((value) => value.length >= 2 && !isDeliveryOrStyleRequirement(value) && !isSyntheticChapterRequirement(value));
}

export function getWordIntentKeywordCoverage(plan: WordDocumentPlan, intent?: WordGenerationIntent): WordIntentKeywordCoverage {
  const keywords = significantIntentKeywords(intent);
  const coreKeywords = coreIntentKeywords(intent);
  const compactText = compact(textFromPlan(plan));
  const matchedKeywords: string[] = [];
  const missingKeywords: string[] = [];
  const missingCoreKeywords: string[] = [];

  for (const keyword of keywords) {
    if (keywordMatches(compactText, keyword)) {
      matchedKeywords.push(keyword);
    } else {
      missingKeywords.push(keyword);
      if (coreKeywords.some((core) => compact(core) === compact(keyword))) missingCoreKeywords.push(keyword);
    }
  }

  const coreMatched = coreKeywords.length === 0 || coreKeywords.some((keyword) => keywordMatches(compactText, keyword));
  const coverageScore = keywords.length ? Math.round((matchedKeywords.length / keywords.length) * 100) : 100;
  return {
    coverageScore,
    coreMatched,
    matchedKeywords,
    missingCoreKeywords,
    missingKeywords,
    totalKeywords: keywords.length
  };
}

function groundingIntentKeywords(intent?: WordGenerationIntent) {
  if (!intent) return [];
  const identity = new Set([
    intent.topic,
    intent.chapter,
    intent.duration,
    intent.audience,
    intent.lengthRequirement
  ].map((item) => compact(cleanText(item, 80))).filter(Boolean));
  return uniqueValues([
    intent.purpose,
    intent.chapterTitle,
    ...splitIntentItems(intent.scope),
    ...intent.mustInclude.flatMap(splitIntentItems),
    ...intent.requirements.flatMap(splitIntentItems),
    ...intent.keywords.flatMap(splitIntentItems)
  ].filter((value): value is string => Boolean(value))).filter((value) => {
    const key = compact(value);
    return key && !identity.has(key) && !isDeliveryOrStyleRequirement(value) && !isSyntheticChapterRequirement(value) && !/^(教案|报告|方案|总结|文档|文件|课时|页数|表格|清单|列表|步骤清单)$/.test(value);
  });
}

function countRepeatedPhrases(text: string) {
  const phrases = text.match(/[\u4e00-\u9fa5]{4,12}/g) || [];
  const counts = new Map<string, number>();
  for (const phrase of phrases) counts.set(phrase, (counts.get(phrase) || 0) + 1);
  const allowedRepeated = [
    "教学过程",
    "评价标准",
    "实施步骤",
    "年度运营复盘",
    "复盘结论",
    "责任分工",
    "基础数据",
    "后续动作",
    "当前情况",
    "风险影响",
    "运营复盘",
    "基础数据",
    "责任追踪",
    "管理层",
    "跨团队",
    "后续优先级",
    "复盘判断"
  ];
  const threshold = Math.max(8, Math.ceil(compact(text).length / 1500));
  return [...counts.entries()].filter(
    ([phrase, count]) =>
      count >= threshold &&
      !allowedRepeated.some((allowed) => phrase.includes(allowed) || allowed.includes(phrase)) &&
      !/(责任|复盘|数据|风险|后续|运营|专题|协同|结论|动作|记录|管理|资源|团队|判断|影响|规律|目标|评价|课程|教学|任务|练习|活动)/.test(phrase)
  );
}

function ngramSimilarity(leftValue: string, rightValue: string) {
  const grams = (value: string) => {
    const compactText = compact(value);
    const result = new Set<string>();
    for (let index = 0; index <= compactText.length - 10; index += 1) {
      result.add(compactText.slice(index, index + 10));
    }
    return result;
  };
  const left = grams(leftValue);
  const right = grams(rightValue);
  if (!left.size || !right.size) return 0;
  let overlap = 0;
  for (const item of left) {
    if (right.has(item)) overlap += 1;
  }
  return overlap / Math.min(left.size, right.size);
}

function findHighlySimilarSections(plan: WordDocumentPlan) {
  const sections = contentSectionsForGrounding(plan)
    .map((section) => ({ heading: section.heading, text: textFromSection(section) }))
    .filter((section) => compact(section.text).length > 80);
  const pairs: Array<{ left: string; right: string; similarity: number }> = [];
  for (let leftIndex = 0; leftIndex < sections.length; leftIndex += 1) {
    for (let rightIndex = leftIndex + 1; rightIndex < sections.length; rightIndex += 1) {
      const similarity = ngramSimilarity(sections[leftIndex].text, sections[rightIndex].text);
      if (similarity >= 0.72) pairs.push({ left: sections[leftIndex].heading, right: sections[rightIndex].heading, similarity });
    }
  }
  return pairs;
}

